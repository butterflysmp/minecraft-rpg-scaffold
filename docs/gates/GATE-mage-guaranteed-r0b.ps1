# GATE-mage-guaranteed R0b: the deployed jar carries PR A, C, D, E and the gate. Prediction: before '--- controls',
# 28 PRESENT and 0 ABSENT; after it, 6 ABSENT and 0 PRESENT. Run: powershell -File <this> [-JarPath <jar>]
param([string]$JarPath = 'run\plugins\rpg-0.1.0-SNAPSHOT.jar')
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zip = [IO.Compression.ZipFile]::OpenRead((Resolve-Path $JarPath))
function Bytes($name) { $e = $zip.GetEntry($name); if ($e -eq $null) { return $null }; $s = $e.Open(); $m = New-Object IO.MemoryStream; $s.CopyTo($m); $s.Close(); [Text.Encoding]::GetEncoding(28591).GetString($m.ToArray()) }
function ValueLine($text, $l, $label) { if ($text -ne $null -and $text -match ("(?m)^" + [regex]::Escape($l) + '([ \t]*\r?$|[ \t]+#)')) { "PRESENT $label '$l'" } else { "ABSENT  $label '$l'" } }
function Has($text, $s, $label) { if ($text -ne $null -and $text.Contains($s)) { "PRESENT $label '$s'" } else { "ABSENT  $label '$s'" } }
$ls = Bytes 'content/enchants/large_sparks.yml'
$sc = Bytes 'content/enchants/sharp_crystals.yml'
$ps = Bytes 'content/enchants/polished_scepter.yml'
$eb = Bytes 'content/enchants/echo_beam.yml'
$et = Bytes 'content/enchants/early_toll.yml'
$wf = Bytes 'content/enchants/wildfire.yml'
$ce = Bytes 'content/weapons/cursed_emerald.yml'
$fs = Bytes 'content/weapons/flint_staff.yml'
$i = Bytes 'selftest/index.yml'
$g = Bytes 'selftest/GATE-mage-guaranteed.yml'
$ct = Bytes 'io/github/butterflysmp/rpg/core/ability/CastTunes.class'
$hc = Bytes 'io/github/butterflysmp/rpg/core/enchant/HitChains.class'
$el = Bytes 'io/github/butterflysmp/rpg/paper/content/EnchantLoader.class'
$pw = Bytes 'io/github/butterflysmp/rpg/paper/adapter/PaperCombatWorld.class'
$wfc = Bytes 'io/github/butterflysmp/rpg/paper/weapon/WeaponFire.class'
$sd = Bytes 'io/github/butterflysmp/rpg/paper/selftest/SelfTestDrivers.class'
ValueLine $ls 'effect: cast_tune' 'large_sparks.yml'
ValueLine $ls 'weapon: flint_staff' 'large_sparks.yml'
ValueLine $ls 'guaranteed: true' 'large_sparks.yml'
ValueLine $ls '  quantity: damage' 'large_sparks.yml'
ValueLine $ls '  value_by_level: [4, 8, 12]' 'large_sparks.yml'
ValueLine $sc '  value_by_level: [3, 6, 9]' 'sharp_crystals.yml'
ValueLine $ps '  quantity: range' 'polished_scepter.yml'
ValueLine $eb '  quantity: shots' 'echo_beam.yml'
ValueLine $eb '  value_by_level: [4, 5, 6]' 'echo_beam.yml'
ValueLine $et '  quantity: windup' 'early_toll.yml'
ValueLine $et '  value_by_level: [2, 4, 8]' 'early_toll.yml'
ValueLine $wf 'effect: hit_chain' 'wildfire.yml'
ValueLine $wf '  window_ticks: 60' 'wildfire.yml'
ValueLine $wf '  cap_percent: 60' 'wildfire.yml'
ValueLine $wf '  step_percent_by_level: [5, 10, 15]' 'wildfire.yml'
ValueLine $ce '      shots: 3' 'cursed_emerald.yml'
ValueLine $ce '      - "Channel, then loose three"' 'cursed_emerald.yml'
ValueLine $fs '  - "create fire by flinging mana into flint."' 'flint_staff.yml'
ValueLine $i '  - mage-guaranteed' 'index.yml'
ValueLine $g 'MG1:' 'GATE-mage-guaranteed.yml'
ValueLine $g 'MG10:' 'GATE-mage-guaranteed.yml'
ValueLine $g 'MG11:' 'GATE-mage-guaranteed.yml'
Has $ct '/right_click' 'CastTunes.class'
Has $hc 'forgetPlayer' 'HitChains.class'
Has $el 'right click has' 'EnchantLoader.class'
Has $pw 'VOLLEYSHOT caster=%s source=%s shot=%d pressed=%d tick=%d' 'PaperCombatWorld.class'
Has $wfc 'getCurrentTick' 'WeaponFire.class'
Has $sd 'chains=forgotten' 'SelfTestDrivers.class'
'--- controls'
ValueLine $ce '      shots: 6' 'cursed_emerald.yml CONTROL-OLD'
ValueLine $fs '  - "create fire by slamming mana into flint."' 'flint_staff.yml CONTROL-OLD'
ValueLine $g 'MG12:' 'GATE-mage-guaranteed.yml CONTROL-NONE'
ValueLine $i '  - mage-guarante' 'index.yml CONTROL-PREFIX'
ValueLine $wf '  cap_percent: 6' 'wildfire.yml CONTROL-PREFIX'
Has $pw 'VOLLEYSHOT caster=%s source=%s shot=%d tick=' 'PaperCombatWorld.class CONTROL-SWAPPED'
$zip.Dispose()
